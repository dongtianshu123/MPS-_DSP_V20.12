#ifndef __UART1MODBUS_H__
#define __UART1MODBUS_H__

/* ========================================================================= */
/* 协议物理与逻辑参数配置                                                    */
/* ========================================================================= */
#define MODBUS_SLAVE_ID         0x01    // 本机从站地址
#define MODBUS_BAUDRATE         9600    // 通讯波特率

/* ========================================================================= */
/* 寄存器内存映射边界定义                                                    */
/* ========================================================================= */
#define MODBUS_REG_TOTAL_NUM    160

// 区域1：只读数据区 (对应地址 40001 - 40080，数组索引 0 - 79)
#define REG_RO_START_INDEX      0       
#define REG_RO_END_INDEX        79      

// 区域2：读写设定区 (对应地址 40081 - 40160，数组索引 80 - 159)
#define REG_RW_START_INDEX      80      
#define REG_RW_END_INDEX        159     

/* ========================================================================= */
/* 全局变量外部声明                                                          */
/* ========================================================================= */
extern unsigned int Modbus_Regs[MODBUS_REG_TOTAL_NUM];

/* ========================================================================= */
/* 32位数据安全访问宏 (避免指针强转带来的对齐与大小端风险)                   */
/* ========================================================================= */
/* 默认触摸屏发送 32 位数据的规则为：高字在前 (High Word First) */

#define GET_REG_32BIT(base_index) \
    ( ((unsigned long)Modbus_Regs[(base_index)] << 16) | ((unsigned long)Modbus_Regs[(base_index) + 1]) )

#define SET_REG_32BIT(base_index, val32) \
    do { \
        Modbus_Regs[(base_index)]     = (unsigned int)(((unsigned long)(val32) >> 16) & 0xFFFF); \
        Modbus_Regs[(base_index) + 1] = (unsigned int)((unsigned long)(val32) & 0xFFFF); \
    } while(0)

/* ========================================================================= */
/* 核心 API 函数声明                                                         */
/* ========================================================================= */

extern void Modbus_UART_Init(void);
extern void Modbus_Process_10ms_Task(void);

#endif /* __UART1MODBUS_H__ */